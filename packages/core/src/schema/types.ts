/**
 * Schema v1 — public data types.
 *
 * A document is a plain JSON object: metadata plus a flat block map. The
 * page content is ONE FLAT SEQUENCE per page (the root sequence, a cell's
 * mini-doc sequence, a frame's nested page); nesting is the optional
 * `indent` attribute relative to the preceding block of the same sequence.
 * `children` is the structural order of the true containers (root,
 * table-row, table-cell, surface, frame) and the LEGACY nesting form of the
 * remodeled page types (readable, normalized to `indent` on load; the
 * writer never emits it). The JSON form and the CRDT form are isomorphic:
 * every field has exactly one CRDT image.
 */
import type { Block } from "./block-union";

/** Block identifier (nanoid, generated by the change author; never reused). */
type BlockId = string;

/** The set of marks applied to a run. */
interface MarkSet {
  bold?: true;
  italic?: true;
  strike?: true;
  underline?: true;
  /** Exclusive: never coexists with other marks on the same run. */
  code?: true;
  /** http/https URL or relative path. */
  link?: { href: string };
  /** Text color, hex `#RRGGBB` (alpha optional). */
  color?: { value: string };
  /** Text highlight, hex `#RRGGBB` (alpha optional). */
  highlight?: { value?: string };
  /** Inline formula (KaTeX-compatible source). Exclusive. */
  math?: { tex: string };
}

/** All mark names. */
type MarkName = keyof MarkSet;

/** An inline text run: a span of text with the marks applied to it. */
interface TextRun {
  text: string;
  marks: MarkSet;
}

/** Inline text content of a block: an array of runs. */
type BlockContent = TextRun[];

/** The horizontal alignment of a block's text content. */
type TextAlign = "left" | "center" | "right";

/** Document metadata. */
interface DocMeta {
  /** Schema version. */
  v: 1;
  /** Document identifier (nanoid). */
  id: string;
  /** Document title (empty string is a valid state). */
  title: string;
  /** Creation time, ISO 8601. */
  createdAt: string;
}

/** Document in the public JSON format. */
interface DocJSON extends DocMeta {
  /** Flat map: block id -> block. Order lives in `children`. */
  blocks: Record<BlockId, Block>;
}

/** The flat-page nesting depth of a page block relative to the preceding block of the same sequence (default 0). */
type PageIndent = number;

interface HeadingAttrs {
  /** Heading level 1-6. */
  level: 1 | 2 | 3 | 4 | 5 | 6;
  align?: TextAlign;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface ListItemAttrs {
  list: "bullet" | "number" | "task";
  checked?: boolean;
  align?: TextAlign;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface ParagraphAttrs {
  align?: TextAlign;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface CalloutAttrs {
  variant?: "info" | "warning" | "danger";
  align?: TextAlign;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface QuoteAttrs {
  align?: TextAlign;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface CodeAttrs {
  language?: string;
  /** The five-line collapsed view (default false). */
  collapsed?: boolean;
  /** The caption line below the block; the empty string means no caption (attrs are never removed). */
  caption?: string;
  /** The line-number column (default true). */
  lineNumbers?: boolean;
  /** Wrap at the container width instead of horizontal scroll (default true). */
  wrap?: boolean;
  /** The mermaid view mode (default "code"). */
  mermaidMode?: "code" | "preview";
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface LatexAttrs {
  /** Display (block) formula vs inline. */
  display: boolean;
  align?: TextAlign;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface TableCellAttrs {
  align?: TextAlign;
}

interface TableAttrs {
  /** Column count; every row holds exactly `cols` cells. */
  cols: number;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface ImageAttrs {
  /** Opaque blob key (resolved by the consumer). */
  src: string;
  /** Width in px; `null` = natural width. */
  width?: number | null;
  align?: TextAlign;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface EmbedAttrs {
  /** Embed kind; a renderer hint (all kinds render as an iframe in v1). */
  kind: "iframe" | "github" | "figma" | "loom" | "html";
  /** The embedded page URL. */
  src: string;
  /** Accessible title; falls back to the kind in the renderer. */
  title?: string;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface RootBlock {
  type: "root";
  /** Top-level page blocks, in reading order. */
  children: BlockId[];
}

interface ParagraphBlock {
  type: "paragraph";
  attrs?: ParagraphAttrs;
  content?: BlockContent;
  /** LEGACY nesting form (readable v1): normalized to `indent` on load; the writer never emits it. */
  children?: BlockId[];
}

interface HeadingBlock {
  type: "heading";
  attrs: HeadingAttrs;
  content?: BlockContent;
  /** LEGACY nesting form (readable v1): normalized to `indent` on load; the writer never emits it. */
  children?: BlockId[];
}

interface ListItemBlock {
  type: "list-item";
  attrs: ListItemAttrs;
  content?: BlockContent;
  /** LEGACY nesting form (readable v1): nested `list-item` blocks only; normalized to `indent` on load. */
  children?: BlockId[];
}

interface CalloutBlock {
  type: "callout";
  attrs?: CalloutAttrs;
  content?: BlockContent;
  /** LEGACY nesting form (readable v1): normalized to `indent` on load; the writer never emits it. */
  children?: BlockId[];
}

interface QuoteBlock {
  type: "quote";
  attrs?: QuoteAttrs;
  content?: BlockContent;
  /** LEGACY nesting form (readable v1): normalized to `indent` on load; the writer never emits it. */
  children?: BlockId[];
}

interface CodeBlock {
  type: "code";
  attrs?: CodeAttrs;
  content?: BlockContent;
  /** LEGACY nesting form (readable v1): normalized to `indent` on load; the writer never emits it. */
  children?: BlockId[];
}

interface LatexBlock {
  type: "latex";
  attrs: LatexAttrs;
  /** Text is the LaTeX source. */
  content?: BlockContent;
  /** LEGACY nesting form (readable v1): normalized to `indent` on load; the writer never emits it. */
  children?: BlockId[];
}

interface TableBlock {
  type: "table";
  attrs: TableAttrs;
  /** `table-row` blocks only. */
  children?: BlockId[];
}

interface TableRowBlock {
  type: "table-row";
  /** `table-cell` blocks only; exactly the table `cols` count. */
  children?: BlockId[];
}

interface TableCellBlock {
  type: "table-cell";
  attrs?: TableCellAttrs;
  /** Empty content is a valid (empty) cell. */
  content?: BlockContent;
  /** Leaf block types only. */
  children?: BlockId[];
}

interface ImageBlock {
  type: "image";
  attrs: ImageAttrs;
}

interface EmbedBlock {
  type: "embed";
  attrs: EmbedAttrs;
}

/**
 * A sync-embed reference: the master document, optionally narrowed to a
 * block subtree inside it (the subtree's entry list renders).
 */
interface SyncEmbedRef {
  /** The master document id; the consumer resolves the doc from their own store. */
  docId: string;
  /** A subtree root block of the master; absent — the whole master document. */
  blockId?: string;
}

interface SyncEmbedAttrs {
  /** The reference to the master document. */
  ref: SyncEmbedRef;
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface SyncEmbedBlock {
  type: "sync-embed";
  attrs: SyncEmbedAttrs;
}

interface DividerAttrs {
  /** Nesting depth in the page sequence (default 0). */
  indent?: PageIndent;
}

interface DividerBlock {
  type: "divider";
  attrs?: DividerAttrs;
}

